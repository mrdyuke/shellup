// Package prompt owns the interactive prompt choices of Shellup: starship,
// tide (via fisher), or none. Nothing here performs I/O; the caller writes
// the returned strings to the agreed file paths after showing a summary to
// the user.
package prompt

import (
	"fmt"
	"strings"
)

// Kind enumerates the prompt options shown in the interactive menu.
type Kind string

const (
	KindStarship Kind = "starship"
	KindTide     Kind = "tide"
	KindNone     Kind = "none"
)

// Choices is the menu used by the TUI, in presentation order.
var Choices = []Choice{
	{Kind: KindStarship, Description: "Cross-shell prompt configured via starship.toml"},
	{Kind: KindTide, Description: "Famous fish prompt, installed through fisher (v6)"},
	{Kind: KindNone, Description: "Leave the current prompt exactly as it is"},
}

// Choice pairs a menu entry with its one-line description.
type Choice struct {
	Kind        Kind
	Description string
}

// StarshipInitLines are appended to conf.d/shellup.fish when starship is chosen.
func StarshipInitLines() []string {
	return []string{"starship init fish | source"}
}

// MinimalStarshipToml is a small starting configuration. It is only written
// when the user does not already have starship.toml.
func MinimalStarshipToml() string {
	var b strings.Builder
	b.WriteString("# starship.toml generated by Shellup as a starting point.\n")
	b.WriteString("# Full documentation: https://starship.rs/config/\n\n")
	b.WriteString("[character]\n")
	b.WriteString("success_symbol = \"[>](green)\"\n")
	b.WriteString("error_symbol = \"[>](red)\"\n\n")
	b.WriteString("[git_branch]\nformat = \"$branch($symbol $branch )\"\n\n")
	b.WriteString("[cmd_duration]\nmin_time = 2000\n")
	return b.String()
}

// TideConfigFileContent is a small set of defaults written to
// ~/.config/fish/conf.d/shellup-tide.fish. Tide itself stores its settings as
// global variables; the defaults are only applied when the user has never run
// tide configure, so their own choices win afterwards.
func TideConfigFileContent() string {
	var b strings.Builder
	b.WriteString("# Default tide settings written by Shellup.\n")
	b.WriteString("# Tide is installed via fisher; run `fish -c 'tide configure'` for the\n")
	b.WriteString("# interactive wizard. These defaults are skipped once you have run it.\n\n")
	b.WriteString("if not set -q tide_prompt_pad_items\n")
	for _, v := range tideDefaults {
		fmt.Fprintf(&b, "    %s\n", v)
	}
	b.WriteString("end\n")
	return b.String()
}

// tideDefaults mirrors a sane subset of tide's default style so the prompt
// already looks reasonable before the user runs the configurator.
var tideDefaults = []string{
	"set -U tide_prompt_pad_items false",
	"set -U tide_prompt_min_cols 35",
	"set -U tide_left_items virtual_env prompt_char",
	"set -U tide_right_items context time node python rustc java jobs cmd_duration",
	"set -U tide_cmd_duration_color 875AFF",
	"set -U tide_context_color_default yellow",
	"set -U tide_git_color_branch green",
	"set -U tide_time_color brgrey",
}

// TideUserHint is printed in the final summary so users know the next step.
func TideUserHint() string {
	return "Tide was installed without the interactive configuration. Run fish -c 'tide configure' when shell is ready."
}

// Valid reports whether the kind is one of the menu choices.
func (k Kind) Valid() bool {
	switch k {
	case KindStarship, KindTide, KindNone:
		return true
	}
	return false
}
