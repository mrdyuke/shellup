// Package prompt owns the interactive prompt choices of Shellup: starship,
// tide (via fisher), a deterministic generated custom prompt, or none.
// Nothing here performs I/O; the caller writes the returned strings to the
// agreed file paths after showing a summary to the user.
package prompt

import (
	"fmt"
	"strings"
)

// Kind enumerates the prompt options shown in the interactive menu.
type Kind string

const (
	KindStarship Kind = "starship"
	KindTide     Kind = "tide"
	KindCustom   Kind = "custom"
	KindNone     Kind = "none"
)

// Choices is the menu used by the TUI, in presentation order.
var Choices = []Choice{
	{Kind: KindStarship, Description: "Cross-shell prompt configured via starship.toml"},
	{Kind: KindTide, Description: "Famous fish prompt, installed through fisher (v6)"},
	{Kind: KindCustom, Description: "Generated from 4 short questions, no external calls"},
	{Kind: KindNone, Description: "Leave the current prompt exactly as it is"},
}

// Choice pairs a menu entry with its one-line description.
type Choice struct {
	Kind        Kind
	Description string
}

// StarshipInitLines are appended to conf.d/shellup.fish when starship is chosen.
func StarshipInitLines() []string {
	return []string{"starship init fish | source"}
}

// MinimalStarshipToml is a small starting configuration. It is only written
// when the user does not already have starship.toml.
func MinimalStarshipToml() string {
	var b strings.Builder
	b.WriteString("# starship.toml generated by Shellup as a starting point.\n")
	b.WriteString("# Full documentation: https://starship.rs/config/\n\n")
	b.WriteString("[character]\n")
	b.WriteString("success_symbol = \"[>](green)\"\n")
	b.WriteString("error_symbol = \"[>](red)\"\n\n")
	b.WriteString("[git_branch]\nformat = \"$branch($symbol $branch )\"\n\n")
	b.WriteString("[cmd_duration]\nmin_time = 2000\n")
	return b.String()
}

// TideConfigFileContent is a small set of defaults written to
// ~/.config/fish/conf.d/shellup-tide.fish. Tide itself stores its settings as
// global variables; the defaults are only applied when the user has never run
// tide configure, so their own choices win afterwards.
func TideConfigFileContent() string {
	var b strings.Builder
	b.WriteString("# Default tide settings written by Shellup.\n")
	b.WriteString("# Tide is installed via fisher; run `fish -c 'tide configure'` for the\n")
	b.WriteString("# interactive wizard. These defaults are skipped once you have run it.\n\n")
	b.WriteString("if not set -q tide_prompt_pad_items\n")
	for _, v := range tideDefaults {
		fmt.Fprintf(&b, "    %s\n", v)
	}
	b.WriteString("end\n")
	return b.String()
}

// tideDefaults mirrors a sane subset of tide's default style so the prompt
// already looks reasonable before the user runs the configurator.
var tideDefaults = []string{
	"set -U tide_prompt_pad_items false",
	"set -U tide_prompt_min_cols 35",
	"set -U tide_left_items virtual_env prompt_char",
	"set -U tide_right_items context time node python rustc java jobs cmd_duration",
	"set -U tide_cmd_duration_color 875AFF",
	"set -U tide_context_color_default yellow",
	"set -U tide_git_color_branch green",
	"set -U tide_time_color brgrey",
}

// TideUserHint is printed in the final summary so users know the next step.
func TideUserHint() string {
	return "Tide was installed without the interactive configuration. Run fish -c 'tide configure' when shell is ready."
}

// CustomAnswers are the 4 questions of the custom prompt flow.
type CustomAnswers struct {
	NerdFontIcons bool   // fancy glyphs from a Nerd Font
	GitStatus     bool   // show branch and dirty marker
	Theme         string // "dark" or "light"
	ShowDuration  bool   // show last command duration when measurable
}

// Theme names accepted in CustomAnswers.Theme.
const (
	ThemeDark  = "dark"
	ThemeLight = "light"
)

// ValidateCustomAnswers rejects unknown themes early so the generated config
// is always well-formed.
func ValidateCustomAnswers(a CustomAnswers) error {
	if a.Theme != ThemeDark && a.Theme != ThemeLight {
		return fmt.Errorf("unknown theme %q; use %q or %q", a.Theme, ThemeDark, ThemeLight)
	}
	return nil
}

// theme palette for the generated prompt; colors are fish standard ones so
// the prompt renders correctly on every terminal that fish already works on.
type palette struct {
	Path     string
	Git      string
	Dirty    string
	Duration string
	Frame    string
	Ok       string
	Err      string
}

var paletteDark = palette{
	Path: "cyan", Git: "green", Dirty: "yellow", Duration: "blue",
	Frame: "brblack", Ok: "green", Err: "red",
}

var paletteLight = palette{
	Path: "blue", Git: "green", Dirty: "red", Duration: "magenta",
	Frame: "brblack", Ok: "green", Err: "red",
}

// CustomConfigFileContent generates the fish prompt functions from the
// answers. Output is fully deterministic for a given set of answers: the same
// questions produce byte-identical files, with no external calls.
func CustomConfigFileContent(a CustomAnswers) (string, error) {
	if err := ValidateCustomAnswers(a); err != nil {
		return "", err
	}
	p := paletteLight
	if a.Theme == ThemeDark {
		p = paletteDark
	}

	char := "> "
	if a.NerdFontIcons {
		char = "\ue0b1 \ue0b0 " // right arrow separators plus powerline prompt
	}

	var b strings.Builder
	b.WriteString("# Custom fish prompt generated by Shellup from your answers.\n")
	b.WriteString("# Regenerate by running shellup again and choosing custom.\n\n")
	fmt.Fprintf(&b, "# theme: %s, nerd font icons: %t\n\n", a.Theme, a.NerdFontIcons)
	fmt.Fprintf(&b, "function __shellup_prompt_path\n    set_color --bold %s\n    echo -n (prompt_pwd)\n    set_color normal\nend\n\n", p.Path)

	if a.GitStatus {
		fmt.Fprintf(&b, `function __shellup_prompt_git
    command git rev-parse --git-dir >/dev/null 2>&1; or return
    set -l branch (command git branch --show-current 2>/dev/null)
    test -n "$branch"; or set branch "(detached)"
    set_color --bold %s
    echo -n " $branch"
    set -l changes (command git status --porcelain 2>/dev/null | wc -l)
    if test "$changes" -gt 0
        set_color --bold %s
        echo -n "*"
    end
    set_color normal
end

`, p.Git, p.Dirty)
	}

	if a.ShowDuration {
		fmt.Fprintf(&b, `function __shellup_prompt_duration
    test -n "$CMD_DURATION"; or return
    test "$CMD_DURATION" = "0"; and return
    set_color --bold %s
    echo -n " [$CMD_DURATION]"
    set_color normal
end

`, p.Duration)
	}

	b.WriteString("function fish_prompt\n")
	b.WriteString("    set -l last_status $status\n")
	b.WriteString("    __shellup_prompt_path\n")
	if a.GitStatus {
		b.WriteString("    __shellup_prompt_git\n")
	}
	if a.ShowDuration {
		b.WriteString("    __shellup_prompt_duration\n")
	}
	b.WriteString("    set_color normal\n")
	b.WriteString("    echo\n")
	fmt.Fprintf(&b, "    test \"$last_status\" -eq 0; and set_color --bold %s; or set_color --bold %s\n", p.Ok, p.Err)
	fmt.Fprintf(&b, "    echo -n %s\n", quoteFishArgument(char))
	b.WriteString("    set_color normal\n")
	b.WriteString("end\n")
	return b.String(), nil
}

// quoteFishArgument renders a single-quoted fish string; single quotes inside
// are not reachable from the fixed glyph set, so plain quoting is fine.
func quoteFishArgument(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "\\'") + "'"
}

// IndentChoice renders a stable "custom" identifier used by the app code to
// avoid stringly typed spreads across packages.
func (k Kind) Valid() bool {
	switch k {
	case KindStarship, KindTide, KindCustom, KindNone:
		return true
	}
	return false
}
